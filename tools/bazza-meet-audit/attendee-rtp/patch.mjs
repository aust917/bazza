import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const browserAuditHash = "ae847b0123878d5b1171ce4ebb5244a4311a474eec09831548a41a753041a5ea";

const audit = `const bazzaMeetRtpAudit = (() => {
    const receivers = new Set();
    const fields = [
        "totalSamplesReceived",
        "insertedSamplesForDeceleration",
        "removedSamplesForAcceleration",
        "concealedSamples",
        "jitterBufferEmittedCount",
    ];
    let polling = false;

    function register(receiver) {
        if (typeof receiver?.getStats === "function") receivers.add(receiver);
    }

    async function report(client) {
        if (polling || client.ws.readyState !== WebSocket.OPEN) return;
        for (const receiver of receivers) {
            if (receiver.track?.readyState === "ended") receivers.delete(receiver);
        }
        if (!receivers.size) return;
        polling = true;
        try {
            const perfMs = performance.now();
            const reports = await Promise.allSettled([...receivers].map(async receiver => receiver.getStats()));
            const counters = Object.fromEntries(fields.flatMap(field => [[field, 0], [field + "Reports", 0]]));
            let inboundAudioReports = 0;
            let receiverErrors = 0;
            for (const report of reports) {
                if (report.status !== "fulfilled") {
                    receiverErrors++;
                    continue;
                }
                for (const stats of report.value.values()) {
                    if (stats.type !== "inbound-rtp" || stats.kind !== "audio") continue;
                    inboundAudioReports++;
                    for (const field of fields) {
                        if (Number.isSafeInteger(stats[field]) && stats[field] >= 0) {
                            counters[field] += stats[field];
                            counters[field + "Reports"]++;
                        }
                    }
                }
            }
            client.sendJson({
                type: "BazzaPlayoutAudit",
                stage: "inbound-rtp",
                browserEpochMs: performance.timeOrigin,
                perfMs,
                pollDurationMs: performance.now() - perfMs,
                receivers: reports.length,
                receiverErrors,
                inboundAudioReports,
                ...counters,
            });
        } catch (_) { /* diagnostics are optional */ }
        finally { polling = false; }
    }

    return { register, report };
})();

`;

function replaceOnce(source, before, after) {
    const offset = source.indexOf(before);
    if (offset < 0 || source.indexOf(before, offset + before.length) >= 0) {
        throw new Error(`Unexpected browser audit anchor: ${before.split("\n")[0]}`);
    }
    return source.slice(0, offset) + after + source.slice(offset + before.length);
}

export function instrumentRtp(browserAudit) {
    let source = browserAudit.replaceAll("\r\n", "\n");
    if (createHash("sha256").update(source).digest("hex") !== browserAuditHash) {
        throw new Error("Expected exact recorder payload generated by attendee-browser/patch.mjs");
    }
    const helper = "const bazzaMeetAuditBrowser = (() => {";
    source = replaceOnce(source, helper, audit + helper);
    const track = "const handleAudioTrack = async (event) => {";
    source = replaceOnce(source, track, `${track}\n  bazzaMeetRtpAudit.register(event.receiver);`);
    return replaceOnce(source, "    setInterval(() => bazzaMeetAuditBrowser.report(ws), 1000);", `    setInterval(() => {
        void bazzaMeetRtpAudit.report(ws);
        bazzaMeetAuditBrowser.report(ws);
    }, 1000);`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    try {
        const [input, output, extra] = process.argv.slice(2);
        if (!input || !output || extra) throw new Error("Usage: node patch.mjs <browser-audit.js> <new-output.js>");
        writeFileSync(output, instrumentRtp(readFileSync(input, "utf8")), { flag: "wx" });
    } catch (error) {
        console.error(error.message);
        process.exitCode = 1;
    }
}
